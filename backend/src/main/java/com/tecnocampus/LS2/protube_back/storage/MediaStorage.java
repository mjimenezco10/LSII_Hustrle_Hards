package com.tecnocampus.LS2.protube_back.storage;

import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.nio.file.Path;

/**
 * Where the media files (videos, thumbnails and avatars) are kept. Each file has a key, e.g.
 * {@code upload-<uuid>.mp4} or {@code avatars/<uuid>.webp}, and the browser gets it from {@code /media/<key>}.
 * Strategy pattern: {@link LocalMediaStorage} (a folder) or {@link S3MediaStorage} (an S3 bucket), chosen with
 * {@code pro_tube.storage.type} in {@link StorageConfig}.
 */
public interface MediaStorage {

    /**
     * Saves an uploaded file under {@code key}, replacing any file with that key.
     *
     * @throws IOException if the file cannot be stored
     */
    void save(String key, MultipartFile file) throws IOException;

    /**
     * Makes a file of the local video store (generated by {@code tooling/videoGrabber}) available under {@code key}.
     * Does nothing if it is already stored, so it is safe on every startup.
     *
     * @throws IOException if the file cannot be stored
     */
    void importFile(String key, Path file) throws IOException;

    /**
     * Deletes the file with {@code key} if it exists. A file that cannot be deleted only wastes space, so failures are
     * logged instead of thrown.
     */
    void deleteQuietly(String key);
}
